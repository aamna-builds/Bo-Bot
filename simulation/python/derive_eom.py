"""
Derive the equations of motion of a two-wheeled inverted pendulum (TWIP)
with yaw, using Kane's method (sympy.physics.mechanics).

Run:  python derive_eom.py      (needs: pip install sympy)

It prints the mass matrix M(q) and forcing vector F(q, u, T) as plain Python
and writes them to eom_generated.py. The simulator imports that file, so you
only need sympy if you want to re-derive.

Model
-----
Frames:  N  inertial (x fwd, y left, z up)
         A  heading frame: N rotated by yaw psi about N.z
         B  body frame:    A rotated by pitch theta about A.y
            theta > 0  ->  body leans FORWARD (+A.x)
Generalized speeds (minimal, rolling built in):
         u1 = v         forward speed of the axle midpoint
         u2 = theta_dot pitch rate
         u3 = psi_dot   yaw rate
Rolling without slip:
         r * alphaL_dot = v - (d/2) psi_dot      (alpha = absolute wheel angle about A.y)
         r * alphaR_dot = v + (d/2) psi_dot
Inputs:  TL, TR  torque the gearbox applies to the LEFT/RIGHT wheel about A.y
         (the equal and opposite reaction acts on the body).
Bodies:  chassis (mass mb, COM at l*B.z + e*B.x from the axle midpoint,
         central inertia Ixx, Iyy, Izz, Ixz in B), two wheels (mass mw,
         spin inertia Iwa, transverse inertia Iwt).
Motor rotors are handled outside this rigid-body model (see dynamics.py):
their reflected inertia lives on a separate gear/backlash DOF.
"""
import sympy as sm
import sympy.physics.mechanics as me

t = me.dynamicsymbols._t
psi, theta = me.dynamicsymbols("psi theta")
u1, u2, u3 = me.dynamicsymbols("u1 u2 u3")

mb, mw, l, e, r, d, g = sm.symbols("mb mw l e r d g", positive=True)
Ixx, Iyy, Izz, Ixz, Iwa, Iwt = sm.symbols("Ixx Iyy Izz Ixz Iwa Iwt")
TL, TR = sm.symbols("TL TR")

N = me.ReferenceFrame("N")
A = N.orientnew("A", "Axis", (psi, N.z))
B = A.orientnew("B", "Axis", (theta, A.y))

# angular velocities expressed with generalized speeds
A.set_ang_vel(N, u3 * N.z)
B.set_ang_vel(N, u3 * A.z + u2 * A.y)

O = me.Point("O")
O.set_vel(N, 0)
C = O.locatenew("C", 0)            # axle midpoint (position irrelevant, only velocity)
C.set_vel(N, u1 * A.x)

G = C.locatenew("G", l * B.z + e * B.x)   # chassis COM
G.v2pt_theory(C, N, B)

WLc = C.locatenew("WLc", (d / 2) * A.y)
WRc = C.locatenew("WRc", -(d / 2) * A.y)
WLc.v2pt_theory(C, N, A)
WRc.v2pt_theory(C, N, A)

# wheel frames: spin about A.y. Wheels are axisymmetric, so only angular
# velocity matters; create frames with explicit angular velocity.
WL = me.ReferenceFrame("WL")
WR = me.ReferenceFrame("WR")
WL.orient(A, "Axis", (0, A.y))
WR.orient(A, "Axis", (0, A.y))
wL = (u1 - (d / 2) * u3) / r
wR = (u1 + (d / 2) * u3) / r
WL.set_ang_vel(N, u3 * A.z + wL * A.y)
WR.set_ang_vel(N, u3 * A.z + wR * A.y)

IB = me.inertia(B, Ixx, Iyy, Izz, 0, 0, Ixz)
IW_L = me.inertia(A, Iwt, Iwa, Iwt)   # axisymmetric -> constant in A
IW_R = me.inertia(A, Iwt, Iwa, Iwt)

body = me.RigidBody("body", G, B, mb, (IB, G))
wheelL = me.RigidBody("wheelL", WLc, WL, mw, (IW_L, WLc))
wheelR = me.RigidBody("wheelR", WRc, WR, mw, (IW_R, WRc))

forces = [
    (G, -mb * g * N.z),
    (WLc, -mw * g * N.z),
    (WRc, -mw * g * N.z),
    (WL, TL * A.y),
    (WR, TR * A.y),
    (B, -(TL + TR) * A.y),
]

kd = [theta.diff(t) - u2, psi.diff(t) - u3]
KM = me.KanesMethod(N, q_ind=[theta, psi], u_ind=[u1, u2, u3], kd_eqs=kd)
fr, frstar = KM.kanes_equations([body, wheelL, wheelR], forces)

M = sm.simplify(KM.mass_matrix)
F = sm.simplify(KM.forcing)

# --- pretty code generation -------------------------------------------------
th, U1, U2, U3 = sm.symbols("th U1 U2 U3")
rep = {u1: U1, u2: U2, u3: U3, theta: th, psi: sm.Symbol("ps")}
M = M.xreplace(rep)
F = F.xreplace(rep)
s, c = sm.symbols("s c")
M = M.xreplace({sm.sin(th): s, sm.cos(th): c})
F = F.xreplace({sm.sin(th): s, sm.cos(th): c})
M = M.applyfunc(sm.expand)
F = F.applyfunc(lambda x: sm.collect(sm.expand(x), [TL, TR]))

lines = [
    '"""AUTO-GENERATED by derive_eom.py -- do not edit by hand."""',
    "from math import sin, cos",
    "",
    "",
    "def mass_forcing(th, U1, U2, U3, TL, TR, p):",
    '    """Return (M, F) with  M @ [dU1, dU2, dU3] = F.',
    "    th: pitch [rad], U1: v [m/s], U2: pitch rate, U3: yaw rate [rad/s].",
    '    TL/TR: gearbox torque on left/right wheel [N m]."""',
    "    mb, mw, l, e, r, d, g = p.mb, p.mw, p.l, p.e, p.r, p.d, p.g",
    "    Ixx, Iyy, Izz, Ixz, Iwa, Iwt = p.Ixx, p.Iyy, p.Izz, p.Ixz, p.Iwa, p.Iwt",
    "    s, c = sin(th), cos(th)",
]
for i in range(3):
    for j in range(3):
        lines.append(f"    M{i}{j} = {sm.pycode(M[i, j]).replace('math.', '')}")
for i in range(3):
    lines.append(f"    F{i} = {sm.pycode(F[i]).replace('math.', '')}")
lines.append("    return ((M00, M01, M02), (M10, M11, M12), (M20, M21, M22)), (F0, F1, F2)")
code = "\n".join(lines) + "\n"

if __name__ == "__main__":
    import os
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "eom_generated.py")
    with open(out, "w") as f:
        f.write(code)
    print(code)
    print("written", out)
